# За модуль студент сдал пять практических работ, каждая оценивается максимум в 10 баллов.
# Вводятся баллы за пять работ (дробные, например 8.5) и минимальная сумма для зачёта (целая). Выведите:
# — сумму баллов с одним знаком после точки и максимум 50, как в примерах;
# — средний балл с двумя знаками после точки;
# — средний балл, округлённый функцией round() до десятых;
# — сколько процентов от максимума набрано, с одним знаком после точки;
# — получен ли зачёт: сумма не меньше минимальной;
# — последней строкой баллы через « + », затем « = » и сумму, округлённую round() до десятых.
# Эту строку напечатайте двумя вызовами print().



# Решение

work1 = float(input("баллы за первую работу: "))
work2 = float(input("баллы за вторую работу: "))
work3 = float(input("баллы за третью работу: "))
work4 = float(input("баллы за четвертую работу: "))
work5 = float(input("баллы за пятую работу: "))
exam = int(input("минимальная сумма для зачета: "))

work = work1 + work2 + work3 + work4 + work5
average = (work1 + work2 + work3 + work4 + work5) / 5
percent = work / 50 * 100

print(f"Сумма: {round(work, 2)} из 50")
print(f"Средний балл: {average:.2f}")
print(f"Средний балл: {round(average, 1)}")
print(f"Выполнено: {percent:.1f}%")

if work >= exam:
    print(f"Зачёт: True")
else:
    print(f"Зачёт: False")
print(f"{work1:.1f} + {work2:.1f} + {work3:.1f} + {work4:.1f} + {work5:.1f} = {round(work, 1)}")
