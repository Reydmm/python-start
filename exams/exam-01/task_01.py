# Бассейн продаёт разовые посещения и абонемент на месяц. Вводятся цена одного посещения,
# цена абонемента и число посещений в месяц — все целые.
# Выведите, сколько стоят все разовые посещения за месяц, цену абонемента, экономию с абонементом за месяц и за год.
# Экономия может быть отрицательной — тогда абонемент невыгоден.


# Решение
dropmonts = int(input("месячный абонимент: ")) #сколько стоит месячный абонимент
dropsingle = int(input("разовое посещение: ")) #сколько стоит разовое посещение
quantity = int(input("количество посещений в месяц:")) #сколько человек ходит в месяц

costmonts = dropsingle * quantity - dropmonts
costyears = costmonts * 12
costDropSingleMonth = dropsingle * quantity


print(f"разовые посещения в месяц: {costDropSingleMonth} руб.")
print(f"месячный абонимент: {dropmonts} руб.")
print(f"выгода в месяц: {costmonts} руб.")
print(f"выгода в год: {costyears} руб.")