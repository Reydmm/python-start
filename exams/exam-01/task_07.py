# Студент копит на наушники. Вводятся сумма в копилке, сколько он добавляет каждую неделю и цена наушников
# — все целые. Три недели подряд студент пополняет копилку: каждое пополнение — отдельная строка составного присваивания.
# Выведите сумму после трёх недель, хватает ли денег на наушники и совпадает ли сумма с ценой точно.
# Затем студент покупает наушники: уменьшите сумму составным присваиванием и выведите остаток.
# Покупку считайте в любом случае, тогда остаток может быть отрицательным — это долг.

# Решение

piggyBank = int(input("Сумма в копилке: "))
weekBank = int(input("сколько добавляет каждую неделю: "))
headphones = int(input("цена наушников: "))

weekBank3 = (weekBank * 3) + piggyBank
print(f"Через три недели: {weekBank3}")

if weekBank3 > headphones:
    print(f"Хватает на наушники: True")
else:
    print("False")

if weekBank3 == headphones:
     print(f"Хвататет ровно: True")
else:
    print(f"False")

remainder = weekBank3 - headphones
print(f"Остаток после покупки: {remainder}")

