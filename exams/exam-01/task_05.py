# Счётчик воды показывает, сколько кубометров израсходовано с момента установки.
# Вводятся показания в прошлом месяце и в этом (целые), цена одного кубометра и абонентская плата (дробные).
# Выведите расход за месяц, стоимость воды, сумму к оплате вместе с абонентской платой и средний расход в день,
# если в месяце 30 дней. Денежные суммы и расход в день выводите с двумя знаками после точки.

# Решение

monthlast = int(input("показания за прошлый месяц: "))
month = int(input("показания в этом месяце: "))
cubometr = float(input("цена одного кубометра: "))
payment = float(input("абонентская плата: "))

waterRashod = month - monthlast
costWater = waterRashod * cubometr
cost = payment + costWater
dayrashod = waterRashod / 30

print(f"Расход, куб. м: {waterRashod}")
print(f"Стоимость воды: {costWater:.2f} руб.")
print(f"К оплате: {cost:.2f} руб.")
print(f"В среднем в день: {dayrashod:.2f} руб. м")
