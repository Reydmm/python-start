# Чтобы сравнивать упаковки разного веса, магазин печатает на ценнике цену за 100 грамм.
# Вводятся цена упаковки (дробная) и вес упаковки в граммах (целый).
# Выведите цену за 100 г с двумя знаками после точки, цену за килограмм,
# округлённую функцией round() до десятых, и цену упаковки, округлённую round() до целых рублей.

# Решение

costPack = float(input("цена упаковки: "))
weight = int(input("вес упаковки в граммах: "))

price100 = costPack / weight * 100
price1000 = costPack / weight * 1000

print(f"За 100 г: {round(price100, 2)} руб.")
print(f"За 1 кг: {round(price1000, 1)} руб.")
print(f"Упаковка, округленно: {round(costPack)} руб.")