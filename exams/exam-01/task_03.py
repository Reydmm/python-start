# Кинотеатр печатает подтверждение покупки. Вводятся название фильма, номер ряда, номер первого места,
# число билетов и цена одного билета — все числа целые. Места идут подряд. Выведите две строки,
# как в примерах, с помощью f-строк. Номер последнего места и сумму к оплате посчитайте
# выражениями прямо в фигурных скобках.


# Решение
name = input("введите имя: ")
row = int(input("введите ряд: "))
place = int(input("номер первого места: "))
quantity = int(input("количество билетов: "))
cost = int(input("цена одного билета: "))

place2 = place + quantity - 1
payment = quantity * cost

print(f" «{name}», ряд {row}, места с {place} по {place2} ")
print(f" {quantity} шт. по {cost} руб., к оплате {payment} руб.")