# Магазин канцтоваров печатает чек на три позиции. Вводятся данные трёх позиций:
# для каждой — название, цена (дробная) и количество (целое). Затем вводятся скидка в процентах и сумма,
# начиная с которой доставка бесплатная (обе целые). Выведите чек, как в примерах:
# — три строки позиций: название, количество, цена и стоимость позиции, деньги — с двумя знаками после точки;
# — разделитель из 30 дефисов, получите его повтором строки;
# — сумму без скидки, размер скидки в рублях и сумму к оплате — с двумя знаками;
# — сколько всего единиц в заказе;
# — среднюю цену одной единицы после скидки, округлённую функцией round() до сотых;
# — бесплатна ли доставка: сумма к оплате не меньше порога.

# Решение

name1 = input("Товар 1: ")
price1 = float(input("Цена: "))
count1 = int(input("Количество: "))

name2 = input("Товар 2: ")
price2 = float(input("Цена: "))
count2 = int(input("Количество: "))

name3 = input("Товар 3: ")
price3 = float(input("Цена: "))
count3 = int(input("Количество: "))

discount = int(input("Скидка: "))
delivery = int(input("Бесплатная доставка от: "))

total = price1 * count1 + price2 * count2 + price3 * count3
sale = total * discount / 100
pay = total - sale

units = count1 + count2 + count3

print(f"{name1}: {count1} шт. = {price1 * count1:.2f}")
print(f"{name2}: {count2} шт. = {price2 * count2:.2f}")
print(f"{name3}: {count3} шт. = {price3 * count3:.2f}")

print("-" * 30)

print(f"Сумма: {total:.2f}")
print(f"Скидка: {sale:.2f}")
print(f"К оплате: {pay:.2f}")
print(f"Всего товаров: {units}")
print(f"Средняя цена: {round(pay / units, 2)}")
print(f"Бесплатная доставка: {pay >= delivery}")