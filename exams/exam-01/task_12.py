# Конференция печатает бейджи участников в рамке из символов. Вводятся имя, фамилия, компания, город, роль участника,
# номер дня конференции (целое) и ширина текста внутри рамки (целое число).
# Ширина всегда не меньше длины самой длинной строки. Выведите карточку, как в примерах:
# — верхняя и нижняя граница: знак +, дефисы на ширину плюс 2, знак +;
# — три строки текста: | , текст, пробелы до заданной ширины, |. Число пробелов посчитайте через len(),
# сами пробелы получите повтором строки;
# — строки текста: «имя фамилия», «компания, город», «роль, день N»;
# — под рамкой — сколько пробелов добавлено в каждую из трёх строк;
# — помещается ли карточка в строку из 40 символов: полная ширина карточки — это ширина текста плюс 4.

# Решение

name = input("Имя: ")
surname = input("Фамилия: ")
company = input("Компания: ")
city = input("Город: ")
role = input("Роль: ")
day = input("День: ")
width = int(input("Ширина: "))

name1 = name + " " + surname
name2 = company + ", " + city
name3 = role + ", день " + day

space1 = width - len(name1)
space2 = width - len(name2)
space3 = width - len(name3)

print("+" + "-" * (width + 2) + "+")
print("| " + name1 + " " * space1 + " |")
print("| " + name2 + " " * space2 + " |")
print("| " + name3 + " " * space3 + " |")
print("+" + "-" * (width + 2) + "+")

print("Добавлено пробелов:", space1, space2, space3)
print("Помещается в 40 символов:", width + 4 <= 40)