# Игра составляет ник из имени игрока и года рождения: имя, знак подчёркивания, год. 
# Вводятся имя и год рождения. Год преобразуйте в целое число через int(). 
# Соберите ник сложением строк и выведите: рамку из знаков = длиной с ник, сам ник, такую же рамку,
# длину ника и тип переменной с годом.
# Решение

name = input("введите имя: ")
happyBirsday = int(input("год рождения"))

nickname = name + str(happyBirsday) #мы перевели день рождение в строку
frame = "=" * len(nickname) #лен считает количество символов в строке

print(frame)
print(nickname)
