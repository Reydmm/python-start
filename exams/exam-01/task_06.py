# В браузере открыты три вкладки, слева направо. Вводятся их названия.
# Выведите порядок вкладок, затем поменяйте местами первую и третью вкладку и выведите порядок ещё раз.
# После этого последнюю вкладку перетаскивают в начало, остальные сдвигаются вправо.
# Выведите итоговый порядок. Каждое изменение порядка запишите одной строкой множественного присваивания,
# без дополнительных переменных.

# Решение

tab1 = input("введите название вкладки: ")
tab2 = input("введите название вкладки: ")
tab3 = input("введите название вкладки: ")

print(f"Было: {tab1}, {tab2}, {tab3}")

tab1, tab2, tab3 = tab3, tab2, tab1
print(f"Обмен крайних: {tab1}, {tab2}, {tab3}")

tab1, tab2, tab3 = tab3, tab1, tab2
print(f"Последняя в начало: {tab1}, {tab2}, {tab3}")
