# Вводятся день, месяц и год — как текст, без преобразования в числа.
# Выведите три строки: дату через точку (день.месяц.год),
# дату через дефис в обратном порядке (год-месяц-день) и строку «Сохранено: день/месяц/год». 
# Третью строку напечатайте двумя вызовами print(): первый выводит слово «Сохранено:», второй — дату.
# Каждую часть даты передавайте в print() отдельным аргументом, склеивать строки плюсом нельзя.
# Решение

day = str(input("введите день"))
month = str(input("введите месяц"))
year = str(input("введите год"))

print(f"{day}.{month}.{year}")
print(f"{year}-{month}-{day}")
print(f"Сохранено: {day}/{month}/{year}")