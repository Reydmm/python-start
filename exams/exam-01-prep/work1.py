# В городе можно платить за каждую поездку отдельно или купить проездной на месяц.
# Вводятся цена одной поездки, цена проездного и число поездок в месяц — все целые.
# Выведите, сколько стоят все поездки по отдельности, цену проездного, экономию с проездным за месяц и за год.
# Экономия может быть отрицательной — тогда проездной невыгоден.

fare = int(input("Цена автобусного билета: "))
travelcard = int(input("Цена проездного билета: "))
monthtravel = int(input("сколько раз в месяц ездим: "))

allfare = fare * monthtravel
economic = monthtravel * fare - travelcard
yeareconomic = economic * 12

print(f"Поездки по отдельности: {allfare} руб.")
print(f"Проездной: {travelcard} руб.")
print(f"Экономия за месяц: {economic} руб.")
print(f"Экономия за год: {yeareconomic} руб.")


