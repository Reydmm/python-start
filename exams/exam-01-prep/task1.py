# Стоимость поездки на такси складывается из платы за посадку и платы за каждый километр.
# Вводятся плата за посадку, цена одного километра и длина поездки в километрах — все целые.
# Выведите стоимость поездки

boarding = int(input("Введите цену на посадку: "))
per_km = int(input("цена 1 км., руб.: "))
distance = int(input("Расстояние, км: "))

cost = boarding + (per_km * distance)

print(f"Стоимость поездки {cost} руб.")
