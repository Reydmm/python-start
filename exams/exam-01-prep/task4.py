# Вводятся домен сайта, раздел и страница. Выведите две строки: адрес страницы, где части разделены косой чертой,
# и строку навигации «Вы здесь: раздел > страница». Каждую часть выводите отдельным аргументом print(), 
# склеивать строки плюсом нельзя. Слова «Вы здесь:» печатаются отдельным print().

domain = input("Домен: ")
section = input("Раздел: ")
page = input("Страница: ")

print("https:/", domain, section, page, sep = "/") #крч сеп это когда так перечислаем вместо запятых
# ставится то чо в сеп кро последней запятой

print("Вы здесь: ", end = " ") # енд штука нужна для того чтоб этот принт вывелся до второго тут и для этого мы пробел ставим
print(section, page, sep =" > ")