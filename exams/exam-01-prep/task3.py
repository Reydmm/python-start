# Интернет-магазин печатает строку заказа. Вводятся название товара, цена за штуку и количество
# — цена и количество целые. Выведите одну строку, как в примерах,с помощью f-строки.

name = input("Товар: ") # импут это ввод значения
price = int(input("Цена, руб.: ")) # инт значит что значение целое будет
count = int(input("Количество: "))

total = price * count

print(f"{name}: {count} шт.: по {price} руб. = {total} руб. ") # фигурные скобки это специально вместе с f строкой пишется