# В плеере в очереди стоят три песни. Вводятся их названия в порядке воспроизведения.
# Выведите очередь, затем поменяйте местами вторую и третью песню и выведите очередь ещё раз. 
# После этого первую песню переносят в конец очереди, остальные сдвигаются вперёд. Выведите итоговую очередь.
# Каждое изменение очереди запишите одной строкой множественного присваивания, без дополнительных переменных.

song1 = input("первая песня в очереди:")
song2 = input("вторая песня в очереди:")
song3 = input("третья песня в очереди:")

print(f"было: {song1} {song2} {song3}")

song1, song2, song3 = song1, song3, song2
print(f"Обмен второй и третьей: {song1} {song2} {song3}")

song1, song2, song3 = song2, song3, song1
print(f"Первая в конец: {song1} {song2} {song3}")