# Счётчик электричества показывает, сколько киловатт-часов израсходовано с момента установки.
# Вводятся показания в прошлом месяце и в этом (целые), цена одного киловатт-часа и плата за обслуживание (дробные).
# Выведите расход за месяц, стоимость электричества, сумму к оплате вместе с платой за обслуживание
# и средний расход в день, если в месяце 30 дней. Денежные суммы и расход в день выводите с двумя знаками после точки.

thisMonth = int(input("Вводятся показания в этом месяце:"))
lastMonth = int(input("Вводятся показания в прошлом месяце:"))
KilowatHours = float(input("Цена одного киловатт-часа:"))
Price = float(input("плата за обслуживания:"))

counter = lastMonth - thisMonth
PriceElectro = counter * KilowatHours #посчитали цену электричества
full = PriceElectro + Price #cумма вместе с платой за обслуживание
days = 30
day = counter / days #тут средний расход в день если в месяце их 30

print(f"Расход, кВт.ч: {counter:.0f}") # Расход, кВт·ч: 217
print(f"Стоимость электричества: {PriceElectro:.2f} руб.")  #   Стоимость электричества: 1395.31 руб.
print(f"К оплате: {full:.2f} руб.") #посчитали общую плату за месяц с обслуживанием
print(f"В среднем в день: {day:.2f} кВт·ч") 