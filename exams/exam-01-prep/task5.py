# Водитель планирует поездку. Вводятся расстояние в километрах, расход бензина на 100 км в литрах и цена литра— 
# все целые. Выведите, сколько литров понадобится и сколько они будут стоить.

distance = int(input("Расстояние, км: "))
per_100km = int(input("Расход 100 км., л.: "))
price = int(input("Цена литра, руб.: "))

liters = (distance * per_100km) / 100 #тогда мы получим скок надо всего литров
#400 * 5 -> 2000 литров если это на 1 км -> 2000 / 100 -> 20 литров на 100 км
cost = liters * price

print("Понадобится литров: ", liters)
print("Стоимость бензина: ", cost, "руб. ")