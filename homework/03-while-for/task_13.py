# Решение
# Вводится целое число n ≥ 0. Выведите его факториал — произведение чисел от 1 до n — в формате 5! = 120. Факториал 0 равен 1.
n = int(input())
total = 1
for members in range(1, n+1):
    total *= members
print(f"{n}! = {total}")

#получается мы вводим n, тотал уже равен одному, чтобы начинать умножение с цифры 1
#ввели число и от 1 до этого числа (включительно тк +1)
#в мемберс идет запись от 1 до n, последовательно
# дальще тотал который у нас равен 1 умножается на эту последоваельность
