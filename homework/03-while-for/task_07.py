#Программа читает числа до нуля и выводит сумму и количество чисел.
#В программе три ошибки. Исправьте их.

number = int(input("Число (0 — конец): "))
total = 0
count = 0

while number != 0:
    total += number
    count += 1
    number = int(input("Число (0 — конец): "))

print("Сумма:", total)
print("Количество:", count)

