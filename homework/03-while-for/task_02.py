# Фитнес-браслет передаёт количество шагов за каждый день. Вводятся числа шагов по одному, ввод
# заканчивается нулём. Выведите общее число шагов в формате «Всего шагов: 53200».
#
# Каждый input() выводит подсказку. Тексты подсказок — как в примерах, после двоеточия или скобки
# стоит пробел.
#
# Пример 1
#   ввод:
#     8000
#     10500
#     7300
#     0
#   в терминале:
#     Шаги за день (0 — конец): 8000
#     Шаги за день (0 — конец): 10500
#     Шаги за день (0 — конец): 7300
#     Шаги за день (0 — конец): 0
#     Всего шагов: 25800
# Пример 2
#   ввод:
#     0
#   в терминале:
#     Шаги за день (0 — конец): 0
#     Всего шагов: 0
# Пример 3
#   ввод:
#     12000
#     0
#   в терминале:
#     Шаги за день (0 — конец): 12000
#     Шаги за день (0 — конец): 0
#     Всего шагов: 12000

# Решение

total = 0
stap = int(input("начальное число шагов: "))

while stap != 0 % 10 == 0:
  total += stap
  stap = int(input())

print(f"Всего шагов: {total}")

#тотал мы ввели для того, чтобы записывать туд получившиеся шаги в процессе, начальный инпут в стэп это первое число, то есть 
#оно например равно 10 и это не равно 0 как у нас записано !=0 следовательно это загружается в тотал
#второй импут для введение следующего числа шагов, так будет по кругу пока инпут стэп не будет равен 0
#дальше проценты значат что остаток при делении на 10 будет равен 0 (==0)