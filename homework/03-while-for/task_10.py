# Решение

# Вводится число покупок n, затем цена каждой покупки. Выведите общую сумму в формате Итого: 1730 руб.. При n = 0 выведите итого 0.
total = 0
count = 0
n = int(input("введите число покупок: "))
while count != n:
         a = int(input("введите цену покупок: "))
         count += 1
         total += a
         if n == count:
          break
print(f"Итого: {total}")
    
