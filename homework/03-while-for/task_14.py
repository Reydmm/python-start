# Решение
# Датчик передал n показаний температуры (n ≥ 1). Вводится n, затем показания по одному (целые).
# Выведите самое низкое показание и среднее с двумя знаками в формате Минимум: -4 и Среднее: 2.50.
# Функцию min() не используйте.
n = int(input("Количество показаний: "))

count_n = 0
total = 0
min_temp = 0

while count_n < n:
    temp = int(input("Показатель температуры: "))

    total += temp

    if count_n == 0 or temp < min_temp:
        min_temp = temp

    count_n += 1

average = total / n

print(f"Минимум: {min_temp} и Среднее: {average:.2f}")

