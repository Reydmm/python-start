# Программа выводит сумму квадратов чисел от 1 до n включительно. В программе три ошибки.
# Исправьте их.
#
# Каждый input() выводит подсказку. Тексты подсказок — как в примерах, после двоеточия или скобки
# стоит пробел.
#
# Пример 1
#   ввод:
#     3
#   в терминале:
#     Число n: 3
#     Сумма квадратов: 14
# Пример 2
#   ввод:
#     1
#   в терминале:
#     Число n: 1
#     Сумма квадратов: 1
# Пример 3
#   ввод:
#     10
#   в терминале:
#     Число n: 10
#     Сумма квадратов: 385

# Решение: исправьте программу ниже
n = int(input("Число n: "))
total = 0
for number in range(1, n+1):
    total += number ** 2 

print("Сумма квадратов:", total)

#ввод тотал должен быть над циклом, чтобы он каждый раз не обнулялся 
#в тотал просто записывается каждое число до введенного нами числа включительно в квадрате и складывается, например 5 1**2 + 2**2 + 3**2 и так далее до числа n
#это и называется сумма квадратов
